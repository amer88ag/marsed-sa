function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if ((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const inGeometry = (lon, lat, geometry) => geometry.coordinates.some(polygon =>
  inRing(lon, lat, polygon[0]) && !polygon.slice(1).some(hole => inRing(lon, lat, hole)));

