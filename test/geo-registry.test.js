test("city ids are unique and every coordinate documents its source", () => {
  const ids = registry.cities.map(city => city.id);
  assert.equal(new Set(ids).size, ids.length);
  for (const city of registry.cities) {
    assert.ok(city.name_ar && city.coordinate_source, city.id);
    assert.ok(city.groups.length > 0, city.id);
    assert.ok(city.groups.every(group => registry.groups[group]), city.id + " uses a documented group");
  }
});

test("every registry city lies inside the national outline and inside its recorded region", () => {
  const sau = boundary.features[0].geometry;
  for (const city of registry.cities) {
    assert.equal(city.inside_boundary, true, city.id);
    assert.ok(inGeometry(city.lon, city.lat, sau), city.id + " inside simplified outline");
    const region = regions.features.find(feature => feature.properties.id === city.region_id);
    assert.ok(region, city.id + " has a region");
    assert.ok(inGeometry(city.lon, city.lat, region.geometry), city.id + " inside " + city.region_id);
  }
});

test("each of the 13 administrative regions has at least one coverage sampling point", () => {
  assert.equal(registry.regions.length, 13);
  assert.equal(regions.features.length, 13);
  const sampled = new Set(Cities.pointsFor("coverage").map(point => point.region_id));
  for (const region of registry.regions) assert.ok(sampled.has(region.id), region.id);
  assert.deepEqual(Coverage.POINTS.map(p => p.id), Cities.pointsFor("coverage").map(p => p.id));
});

