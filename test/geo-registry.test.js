test("elevation refuses points outside the observatory frame without calling the service", async () => {
  let calls = 0;
  const chain = () => { const o = {}; ["addTo", "setLatLng", "bindPopup", "openPopup", "on", "setView", "setMaxBounds", "setMinZoom"].forEach(m => { o[m] = () => o; }); o.getZoom = () => 5; o.options = {}; return o; };
  const page = runPage("elevation/index.html", {
    L: { map: chain, tileLayer: chain, marker: chain, geoJSON: chain },
    HttpClient: Object.assign({}, require("../src/platform/http/client.js"), { request: async () => { calls++; return { elevation: [10] }; } }),
    CityRegistry: Cities, SaudiMapFrame: Frame
  });
  await flush();
  const boundaryCalls = calls;
  page.$("coords").value = "48.85, 2.35";
  await page.$("searchPoint").fire("click");
  await flush();
  assert.equal(calls, boundaryCalls, "no elevation request for a point in Paris");
  assert.match(page.$("status").textContent, /خارج نطاق المرصد/);
});
